// Energinet's location-based electricity declaration per municipality, as yearly averages
// (docs/adr/0031). Energi Data Service publishes it by the hour in two parts:
// - ReCoverageMunicipality: each municipality's consumption, and the share (%) covered by
//   renewables produced and used locally.
// - DeclarationTransmissionEmission: the emissions per kWh of the rest, from the transmission
//   grid, per price area. Only the 125 % method is used, as for the price areas.
// The year's figure is the consumption-weighted average of
//   (1 − local RE share) × (CO2 + CH4 × 28 + N2O × 265), CH4 and N2O being in mg/kWh,
// which reproduces Energinet's spreadsheet »Miljødeklaration per kommune«.
// Kept apart from the fetch so it can be tested.

export const EDS = 'https://api.energidataservice.dk/dataset'

export type ReCoverageRow = { HourUTC: string; MunicipalityNo: string; REshare: number; ConsumptionkWh: number }
export type TransmissionRow = {
  HourUTC: string
  PriceArea: string
  FuelAllocationMethod: string
  Version: string
  CO2PerkWh: number
  CH4PerkWh: number
  N2OPerkWh: number
}

/** GWP100 the declaration uses (IPCC AR5), as in Energinet's spreadsheet */
export const GWP = { CH4: 28, N2O: 265 }

const versionRank: Record<string, number> = { Initial: 1, Preliminary: 2, Final: 3 }

/** Municipality numbers 101-400 are DK2 and the rest DK1, as Energi Data Service documents them */
export const priceAreaOf = (municipalityNo: string) => (Number(municipalityNo) <= 400 ? 'DK2' : 'DK1')

/**
 * g CO2e/kWh per municipality for one year. Each hour uses the latest version of the
 * transmission emissions. Returns null for a municipality with an hour that has no emissions,
 * or with no consumption, so a gap never passes as a figure.
 */
export function yearlyFactors(re: readonly ReCoverageRow[], transmission: readonly TransmissionRow[]): Map<string, number | null> {
  const perKWh = new Map<string, { rank: number; g: number }>()
  for (const t of transmission) {
    if (t.FuelAllocationMethod !== '125%') continue
    const key = `${t.HourUTC}|${t.PriceArea}`
    const rank = versionRank[t.Version] ?? 0
    if ((perKWh.get(key)?.rank ?? -1) >= rank) continue
    perKWh.set(key, { rank, g: t.CO2PerkWh + (t.CH4PerkWh * GWP.CH4 + t.N2OPerkWh * GWP.N2O) / 1000 })
  }
  const sums = new Map<string, { co2e: number; kWh: number; gap: boolean }>()
  for (const r of re) {
    const s = sums.get(r.MunicipalityNo) ?? { co2e: 0, kWh: 0, gap: false }
    sums.set(r.MunicipalityNo, s)
    const e = perKWh.get(`${r.HourUTC}|${priceAreaOf(r.MunicipalityNo)}`)
    if (!e) { s.gap = true; continue }
    s.co2e += r.ConsumptionkWh * (1 - r.REshare / 100) * e.g
    s.kWh += r.ConsumptionkWh
  }
  return new Map([...sums].map(([no, s]) => [no, s.gap || s.kWh <= 0 ? null : s.co2e / s.kWh]))
}

/** The hours of a calendar year in UTC: 8760, or 8784 in a leap year */
export const hoursIn = (year: number) => ((year % 4 === 0 && year % 100 !== 0) || year % 400 === 0 ? 8784 : 8760)

export function municipalityGridModule(
  years: readonly number[],
  values: Record<string, (number | null)[]>,
  fetched: string,
): string {
  const rows = Object.keys(values).sort((a, b) => Number(a) - Number(b))
    .map((no) => `  '${no}': [${values[no].map((v) => (v === null ? 'null' : v.toFixed(2))).join(', ')}],`)
  return `// Generated by \`npm run municipality-grid\` (scripts/municipality-grid.ts) on ${fetched}. Don't edit by hand.
// Energinet's location-based declaration per municipality, g CO2e/kWh, 125 % method, computed
// from Energi Data Service (ReCoverageMunicipality × DeclarationTransmissionEmission), docs/adr/0031.

export const MUNICIPALITY_GRID_FETCHED = '${fetched}'

export const municipalityGridYears: readonly number[] = [${years.join(', ')}]

/** Statistics Denmark municipality code → g CO2e/kWh per year in municipalityGridYears; null where a year is incomplete */
export const municipalityGridValues: Record<string, readonly (number | null)[]> = {
${rows.join('\n')}
}
`
}
