// Danmarks Statistik's Net Price Index (Nettoprisindeks), table PRIS05, yearly averages, as the
// TypeScript module src/data/netPriceIndex.ts. Kept apart from the fetch so it can be tested.

export const NPI_URL = 'https://api.statbank.dk/v1/data/PRIS05/CSV?lang=da&Tid=*&HOVED=1005'

/** "TID;HOVED;INDHOLD" rows, Danish decimals → year and value, oldest first */
export function parseNpiCsv(csv: string): { year: number; value: number }[] {
  const lines = csv.replace(/^\uFEFF/, '').trim().split(/\r?\n/)
  if (lines[0]?.split(';')[0] !== 'TID') throw new Error(`Unexpected header: ${lines[0]}`)
  return lines.slice(1).map((line) => {
    const [tid, , indhold] = line.split(';')
    const year = Number(tid)
    const value = Number(indhold.replace(',', '.'))
    if (!Number.isInteger(year) || !Number.isFinite(value) || value <= 0) throw new Error(`Unexpected row: ${line}`)
    return { year, value }
  }).sort((a, b) => a.year - b.year)
}

export function npiModule(points: readonly { year: number; value: number }[], fetched: string): string {
  return `// Generated by \`npm run npi\` (scripts/net-price-index.ts) on ${fetched}. Don't edit by hand.
// Danmarks Statistik, Nettoprisindeks (PRIS05), årsgennemsnit: ${NPI_URL}

export const NPI_FETCHED = '${fetched}'

export const npiPoints: readonly { year: number; value: number }[] = [
${points.map((p) => `  { year: ${p.year}, value: ${p.value} },`).join('\n')}
]
`
}
